import puppeteer from 'puppeteer-core';
const URL = 'https://romjjjke.github.io/gruzavtolight/';
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
let p = await b.newPage();
await p.setViewport({ width: 1440, height: 900 });
await p.goto(URL, { waitUntil: 'networkidle2' });
await p.evaluate(() => document.fonts.ready);
await new Promise(r => setTimeout(r, 1100));
await p.screenshot({ path: 'screenshots/desktop-1440.png' });
const stage = await p.evaluate(() => document.querySelector('.bed__grid').getBoundingClientRect().top + window.scrollY);
await p.evaluate(y => window.scrollTo(0, y), stage + 620);
await new Promise(r => setTimeout(r, 1100));
await p.screenshot({ path: 'screenshots/desktop-bed.png' });
await p.evaluate(() => document.querySelector('#raboty').scrollIntoView());
await new Promise(r => setTimeout(r, 900));
await p.screenshot({ path: 'screenshots/desktop-cases.png' });
await p.evaluate(() => document.querySelector('#zayavka').scrollIntoView());
await new Promise(r => setTimeout(r, 900));
await p.screenshot({ path: 'screenshots/desktop-ask.png' });
await p.close();

