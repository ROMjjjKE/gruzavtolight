import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const p = await b.newPage();
await p.setViewport({ width: 1440, height: 900 });
await p.goto('http://127.0.0.1:4220/gruzavtolight/', { waitUntil: 'networkidle2' });
await p.evaluate(() => document.fonts.ready);
await new Promise(r => setTimeout(r, 900));
await p.screenshot({ path: 'shots/g-hero.png' });
const top = await p.evaluate(() => document.querySelector('.bed__grid').getBoundingClientRect().top + window.scrollY);
await p.evaluate(y => window.scrollTo(0, y), top + 700);
await new Promise(r => setTimeout(r, 1000));
await p.screenshot({ path: 'shots/g-bed.png' });
await p.evaluate(() => document.querySelector('#raboty').scrollIntoView());
await new Promise(r => setTimeout(r, 900));
await p.screenshot({ path: 'shots/g-cases.png' });
await b.close();
